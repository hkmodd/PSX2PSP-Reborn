"""Regenerates resources/libcrypt_sbi.tsv.z from the LibCrypt SBI set of psxdatacenter.com.

The .sbi files are redump.org's (http://redump.org): the subchannel Q sectors a LibCrypt disc
deliberately damages, dumped from the real discs. psxdatacenter.com collects them, one 7z per
disc, on its "SBI Files" page (https://psxdatacenter.com/sbifiles.html).

    python -I tools/sbi_import.py <dir> resources/libcrypt_sbi.tsv.z

<dir> holds the page as data:
- rows.json: the page's table in order, a list of {"region", "serials": ["SLES-01226", ...],
  "title", "href"} (href = the row's sbifiles/....7z);
- x/NNN/: the 7z of row NNN (000 = first row) extracted, one <serial>.sbi per disc
  (SLES_012.26.sbi, SCES-01494.sbi, ... separators and case do not matter).

Every file must parse as SBI and the files of a row must be exactly its serials, or nothing is
written. SERIAL_FIXES corrects the page's known serial typos. Output: zlib of a UTF-8 TSV, one line per distinct dump: serial (SLES-01226 form),
title, region, SBI bytes in hex. A serial on two lines = two different dumps that share it
(versions of one disc); identical dumps listed twice are kept once, their titles joined.
"""
import json
import os
import re
import sys
import zlib


# Serials the page gets wrong: (page serial, page title) -> real serial. SLES-02992 is Silent
# Bomber (game DB, pop-fe); Premier Manager 2000 (E) is SLES-02292, whose pop-fe LibCrypt word
# 0x86F2 (redump disc 3619) is exactly the one this SBI encodes.
SERIAL_FIXES = {('SLES-02992', 'PREMIER MANAGER 2000'): 'SLES-02292'}


def key(s):
    return re.sub(r'[^0-9A-Z]', '', s.upper())


def check_sbi(name, d):
    """Raises unless `d` is an SBI as psx2psp-core's subq::parse reads it; returns its sectors."""
    if d[:4] != b'SBI\0':
        raise SystemExit(f'{name}: no SBI header')
    d, n = d[4:], 0
    bcd = lambda b: (b >> 4) * 10 + (b & 15) if b >> 4 < 10 and b & 15 < 10 else None
    while d:
        if len(d) < 4:
            raise SystemExit(f'{name}: truncated entry')
        m, s, f, kind = d[:4]
        size = {1: 10, 2: 3, 3: 3}.get(kind)
        if size is None:
            raise SystemExit(f'{name}: unknown entry type {kind}')
        if len(d) < 4 + size:
            raise SystemExit(f'{name}: truncated entry')
        mm, ss, ff = bcd(m), bcd(s), bcd(f)
        if None in (mm, ss, ff) or ss >= 60 or ff >= 75 or (mm * 60 + ss) * 75 + ff < 150:
            raise SystemExit(f'{name}: bad BCD position {m:02x}:{s:02x}:{f:02x}')
        d, n = d[4 + size:], n + 1
    if not n:
        raise SystemExit(f'{name}: no entries')
    return n


def main():
    src, dest = sys.argv[1], sys.argv[2]
    rows = json.load(open(os.path.join(src, 'rows.json'), encoding='utf-8'))
    dumps = {}  # (serial key, bytes) -> [display serial, [titles], region]
    files = 0
    for i, r in enumerate(rows):
        folder = os.path.join(src, 'x', f'{i:03d}')
        want = {key(s): s for s in r['serials']}
        got = {key(f[:-4]): os.path.join(folder, f) for f in os.listdir(folder) if f.lower().endswith('.sbi')}
        if set(got) != set(want) or len(got) != len(os.listdir(folder)):
            raise SystemExit(f'row {i:03d} {r["title"]}: serials {sorted(want)}, folder has {sorted(os.listdir(folder))}')
        for k, path in sorted(got.items()):
            data = open(path, 'rb').read()
            check_sbi(path, data)
            files += 1
            serial = want[k] if re.fullmatch(r'[A-Z]{4}-\d{5}', want[k]) else f'{k[:4]}-{k[4:]}'
            title, region = ' '.join(r['title'].split()), ' '.join(r['region'].split())
            fixed = SERIAL_FIXES.pop((serial, title), None)
            if fixed:
                print(f'  {serial} ({title}) -> {fixed}')
                serial, k = fixed, key(fixed)
            e = dumps.setdefault((k, data), [serial, [], region])
            if title not in e[1]:
                e[1].append(title)
    if SERIAL_FIXES:
        raise SystemExit(f'serial fixes not applied (page changed?): {SERIAL_FIXES}')
    serials = {k for k, _ in dumps}
    shared = sorted({k for k, _ in dumps if sum(1 for k2, _ in dumps if k2 == k) > 1})
    lines = [
        '# LibCrypt subchannel data: the redump.org .sbi files (http://redump.org), as collected on',
        '# psxdatacenter.com (https://psxdatacenter.com/sbifiles.html). GENERATED by tools/sbi_import.py:',
        f'# do not edit. {len(serials)} serials, {len(dumps)} distinct dumps from {files} files of {len(rows)} rows.',
        '# serial<TAB>title<TAB>region<TAB>SBI bytes in hex',
    ]
    for (k, data), (serial, titles, region) in sorted(dumps.items(), key=lambda kv: (kv[0][0], kv[1][1])):
        lines.append('\t'.join([serial, ' / '.join(titles), region, data.hex()]))
    raw = ('\n'.join(lines) + '\n').encode('utf-8')
    z = zlib.compress(raw, 9)
    with open(dest, 'wb') as f:
        f.write(z)
    print(f'{dest}: {len(serials)} serials, {len(dumps)} dumps, {len(raw)} B text -> {len(z)} B zlib')
    for k in shared:
        print(f'  {k}: ' + ' | '.join(' / '.join(t) for (k2, _), (_, t, _) in sorted(dumps.items()) if k2 == k))


main()
