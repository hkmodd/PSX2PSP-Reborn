//! Patch database: per-game knowledge that no generic rule can derive, kept as editable data.
//!
//! Two kinds of entries, keyed by product code (format: `resources/patches.ini`):
//! - `[game]`: the **POPS config**, the emulator settings block Sony's own PS1 Classics carry in
//!   the PSISOIMG header ([`psar::POPS_CONFIG_AT`]), the **LibCrypt** magic word and the ID POPS
//!   must see. Community data comes from pop-fe.
//! - `[patch]`: **byte patterns** over the disc's data sectors, found by reverse engineering, or
//!   **PPF files** over the raw image, optionally limited to dumps with a given track-1 MD5.
//!
//! The built-in database is compiled in ([`PatchDb::builtin`]). The user file ([`user_path`]) has
//! the same format and is merged on top: its patches win by name, its games by ID. The GUI adds
//! and removes user patches through [`append_user`] / [`remove_user`].
//!
//! [`psar::POPS_CONFIG_AT`]: psx2psp_core::psar::POPS_CONFIG_AT

use std::fmt;
use std::io::Write as _;
use std::path::{Path, PathBuf};
use std::sync::OnceLock;

use psx2psp_core::psar::POPS_CONFIG_MAX;
use psx2psp_patching::{PatternPatch, PatternRule, PpfPatch};

static BUILTIN: &str = include_str!("../../../resources/patches.ini");
/// pop-fe's per-game data (POPS configs, LibCrypt, PPF fixes), generated by
/// `tools/popfe_import.py`; below `patches.ini`. Stored zlib-compressed by `build.rs`.
static POPFE_Z: &[u8] = include_bytes!(concat!(env!("OUT_DIR"), "/popfe.ini.z"));

fn popfe() -> String {
    String::from_utf8(crate::inflate(POPFE_Z)).expect("built-in popfe.ini is UTF-8")
}

/// Name of the POPS config in per-patch choices: it is switched on and off like a patch.
pub const CONFIG: &str = "POPS config";

/// Which preset switch a patch follows.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum Kind {
    /// "Game fixes" (recommended, on by default).
    Fix,
    /// "Unlock fps".
    Fps,
    /// "60 Hz"; when such a patch applies, the POPS config also gets its NTSC flag.
    Ntsc60,
    /// Off unless chosen one by one.
    Other,
}

impl Kind {
    pub const ALL: [Kind; 4] = [Kind::Fix, Kind::Fps, Kind::Ntsc60, Kind::Other];

    /// The `kind =` value in the file.
    pub fn key(self) -> &'static str {
        match self {
            Kind::Fix => "fix",
            Kind::Fps => "fps",
            Kind::Ntsc60 => "60hz",
            Kind::Other => "other",
        }
    }

    fn parse(s: &str) -> Option<Self> {
        Self::ALL.into_iter().find(|k| k.key().eq_ignore_ascii_case(s))
    }
}

impl fmt::Display for Kind {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            Kind::Fix => "Game fix",
            Kind::Fps => "Frame rate",
            Kind::Ntsc60 => "60 Hz",
            Kind::Other => "Other",
        })
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Origin {
    BuiltIn,
    User,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Patch {
    /// Normalised product codes ([`normalise_id`]); empty = every game (`[patch *]`).
    pub ids: Vec<String>,
    pub name: String,
    pub kind: Kind,
    /// `default = off`: left out of its kind's switch, applied only when chosen one by one.
    pub default_on: bool,
    pub body: Body,
    /// Lowercase hex MD5s of track 1 ([`crate::track1_md5`]) of the dumps this patch is for;
    /// empty = any dump.
    pub md5: Vec<String>,
    pub note: String,
    pub origin: Origin,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Body {
    /// A byte pattern over each data sector's user bytes. Normalised hex (`"AB 00 ?? 28"`),
    /// validated as a [`PatternRule`].
    Pattern { search: String, replace: String, align: usize },
    /// A PPF file (validated by [`PpfPatch::parse`]) over the raw image, applied before every
    /// other patch.
    Ppf(Vec<u8>),
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Game {
    pub ids: Vec<String>,
    pub title: String,
    pub config: Option<Vec<u8>>,
    /// Where the config comes from (logged).
    pub source: String,
    pub note: String,
    /// Switches that start on for this game (`default = fix fps 60hz`); without the field only
    /// "Game fixes" does.
    pub switches: Switches,
    /// LibCrypt magic word: POPS answers the protection's subchannel reads from the table
    /// [`psx2psp_core::psar::libcrypt_subchannels`] builds from it.
    pub libcrypt: Option<u16>,
    /// The product code written into the EBOOT instead of the disc's own (pop-fe: Terracon
    /// SCES02836 runs on PSP as SCPS02836).
    pub pops_id: Option<String>,
    /// Lowest deflate level the game loads at on a real PSP (`min_level`): the converter raises
    /// a lower one. See [`psx2psp_core::psar::LEVELS`].
    pub min_level: Option<u32>,
    /// `pal60 = yes`: the game keeps time with a timer, not by counting vblanks, so the native
    /// runtime's "60 Hz" gives its PAL picture 60 vblanks a second instead of applying its `60hz`
    /// patches (an NTSC branch that shows 240 lines of 256-line PAL art).
    pub pal60: Option<bool>,
    /// `disc_swap = manual`: the native runtime leaves the disc change to the player (L+R+SELECT)
    /// instead of changing it when the game waits for a disc; for a game that polls the drive
    /// that way for something else. `auto` (the default) undoes a built-in `manual`.
    pub manual_disc: Option<bool>,
    pub origin: Origin,
}

/// Games and patches in priority order: user entries first ([`PatchDb::with_user`]).
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct PatchDb {
    pub games: Vec<Game>,
    pub patches: Vec<Patch>,
}

#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
#[error("line {line}: {msg}")]
pub struct ParseError {
    pub line: usize,
    pub msg: String,
}

/// `SLES-02895`, `SLES_028.95`, `sles02895` → `SLES02895`.
pub fn normalise_id(id: &str) -> String {
    id.chars().filter(char::is_ascii_alphanumeric).map(|c| c.to_ascii_uppercase()).collect()
}

fn applies_to(ids: &[String], id: &str) -> bool {
    ids.is_empty() || ids.iter().any(|i| i == id)
}

fn overlap(a: &[String], b: &[String]) -> bool {
    a.is_empty() || b.is_empty() || a.iter().any(|x| b.contains(x))
}

/// Canonical form of a pattern (`"ab 0 ??"` is rejected by the rule parser, not here).
fn canonical_hex(s: &str) -> String {
    s.split_whitespace().map(str::to_ascii_uppercase).collect::<Vec<_>>().join(" ")
}

fn hex(b: &[u8]) -> String {
    b.iter().map(|b| format!("{b:02x}")).collect::<Vec<_>>().join(" ")
}

fn parse_bytes(s: &str) -> Result<Vec<u8>, String> {
    s.split_whitespace()
        .map(|t| if t.len() == 2 { u8::from_str_radix(t, 16).ok() } else { None }.ok_or_else(|| format!("bad hex byte `{t}`")))
        .collect()
}

impl Patch {
    /// A validated patch (what the GUI's "Add patch" form builds).
    pub fn new(ids: &[&str], name: &str, kind: Kind, search: &str, replace: &str, note: &str) -> Result<Self, String> {
        let name = name.trim();
        if name.is_empty() {
            return Err("the patch needs a name".into());
        }
        if name.eq_ignore_ascii_case(CONFIG) {
            return Err(format!("“{CONFIG}” is reserved"));
        }
        let (search, replace) = (canonical_hex(search), canonical_hex(replace));
        PatternRule::from_hex(&search, &replace).map_err(|e| e.to_string())?;
        Ok(Self {
            ids: ids.iter().map(|i| normalise_id(i)).filter(|i| !i.is_empty()).collect(),
            name: name.to_owned(),
            kind,
            default_on: true,
            body: Body::Pattern { search, replace, align: 4 },
            md5: Vec::new(),
            note: note.split_whitespace().collect::<Vec<_>>().join(" "),
            origin: Origin::User,
        })
    }

    /// The pattern rule and its alignment; `None` for a PPF patch.
    pub fn pattern(&self) -> Option<(PatternRule, usize)> {
        match &self.body {
            Body::Pattern { search, replace, align } => Some((PatternRule::from_hex(search, replace).expect("patch patterns are validated when parsed"), *align)),
            Body::Ppf(_) => None,
        }
    }

    /// The parsed PPF; `None` for a pattern patch.
    pub fn ppf(&self) -> Option<PpfPatch> {
        match &self.body {
            Body::Ppf(b) => Some(PpfPatch::parse(b).expect("PPF patches are validated when parsed")),
            Body::Pattern { .. } => None,
        }
    }

    /// Whether this patch is for the dump whose track-1 MD5 is `md5` (computed only if needed).
    pub fn for_dump(&self, md5: impl FnOnce() -> String) -> bool {
        self.md5.is_empty() || self.md5.contains(&md5())
    }

    /// Whether this patch is applied: an explicit choice wins, else its kind's switch.
    pub fn wanted(&self, switches: Switches, choices: &[(String, bool)]) -> bool {
        choice(choices, &self.name).unwrap_or(
            self.default_on
                && match self.kind {
                    Kind::Fix => switches.fixes,
                    Kind::Fps => switches.fps,
                    Kind::Ntsc60 => switches.ntsc60,
                    Kind::Other => false,
                },
        )
    }

    /// The `[patch]` section that parses back to this patch.
    pub fn to_ini(&self) -> String {
        let ids = if self.ids.is_empty() { "*".to_owned() } else { self.ids.join(" ") };
        let mut s = format!("[patch {ids}]\nname = {}\nkind = {}\n", self.name, self.kind.key());
        if !self.default_on {
            s += "default = off\n";
        }
        if !self.md5.is_empty() {
            s += &format!("md5 = {}\n", self.md5.join(" "));
        }
        match &self.body {
            Body::Pattern { search, replace, align } => {
                if *align != 4 {
                    s += &format!("align = {align}\n");
                }
                s += &format!("search = {search}\nreplace = {replace}\n");
            }
            Body::Ppf(b) => {
                s += "ppf =\n";
                for line in b.chunks(32) {
                    s += &format!("    {}\n", hex(line));
                }
            }
        }
        if !self.note.is_empty() {
            s += &format!("note = {}\n", self.note);
        }
        s
    }
}

/// The preset switches of a disc.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct Switches {
    pub fixes: bool,
    pub fps: bool,
    pub ntsc60: bool,
}

impl Switches {
    /// Where a game without its own `default` starts: "Game fixes" only. Frame-rate and 60 Hz
    /// patches load POPS harder, so they start on only for games verified on hardware.
    pub const RECOMMENDED: Switches = Switches { fixes: true, fps: false, ntsc60: false };
}

/// The explicit choice for `name` (case-insensitive), if any.
pub fn choice(choices: &[(String, bool)], name: &str) -> Option<bool> {
    choices.iter().rev().find(|(n, _)| n.eq_ignore_ascii_case(name)).map(|c| c.1)
}

/// Whether the game's POPS config is embedded: an explicit choice wins, else "Game fixes".
pub fn config_wanted(switches: Switches, choices: &[(String, bool)]) -> bool {
    choice(choices, CONFIG).unwrap_or(switches.fixes)
}

/// The distinct alignments of the pattern patches among `patches`, sorted.
fn aligns(patches: &[&Patch]) -> Vec<usize> {
    let mut a: Vec<usize> = patches.iter().filter_map(|p| p.pattern().map(|r| r.1)).collect();
    a.sort_unstable();
    a.dedup();
    a
}

/// One [`PatternPatch`] per alignment (normally one), each with its rules in the given order.
/// PPF patches are left out.
pub fn patterns(name: &str, patches: &[&Patch]) -> Vec<PatternPatch> {
    let rules: Vec<(PatternRule, usize)> = patches.iter().filter_map(|p| p.pattern()).collect();
    aligns(patches)
        .into_iter()
        .map(|a| PatternPatch::new(name, rules.iter().filter(|r| r.1 == a).map(|r| r.0.clone()).collect()).aligned(a))
        .collect()
}

/// Maps hits per rule of [`patterns`]' groups back to `patches`' order (0 for a PPF patch).
pub fn hits_per_patch(patches: &[&Patch], group_hits: &[Vec<usize>]) -> Vec<usize> {
    let aligns = aligns(patches);
    let mut next = vec![0usize; aligns.len()];
    patches
        .iter()
        .map(|p| {
            let Some((_, a)) = p.pattern() else { return 0 };
            let g = aligns.binary_search(&a).expect("align is one of the groups");
            let h = group_hits.get(g).and_then(|h| h.get(next[g])).copied().unwrap_or(0);
            next[g] += 1;
            h
        })
        .collect()
}

// ─────────────────────────────── parsing ───────────────────────────────

struct Section<'a> {
    line: usize,
    /// Last line of the section's own fields (for [`remove_user`]).
    end: usize,
    kind: &'a str,
    ids: Vec<&'a str>,
    /// (lowercase key, value, line)
    fields: Vec<(String, String, usize)>,
}

impl Section<'_> {
    fn err(&self, line: usize, msg: impl Into<String>) -> ParseError {
        ParseError { line, msg: msg.into() }
    }

    fn take(&mut self, key: &str) -> Option<(String, usize)> {
        let i = self.fields.iter().position(|f| f.0 == key)?;
        let (_, v, l) = self.fields.remove(i);
        Some((v, l))
    }

    fn require(&mut self, key: &str) -> Result<(String, usize), ParseError> {
        match self.take(key) {
            Some((v, l)) if !v.is_empty() => Ok((v, l)),
            Some((_, l)) => Err(self.err(l, format!("`{key}` is empty"))),
            None => Err(self.err(self.line, format!("[{}] without `{key}`", self.kind))),
        }
    }

    fn ids(&self, any: bool) -> Result<Vec<String>, ParseError> {
        if any && self.ids == ["*"] {
            return Ok(Vec::new());
        }
        if self.ids.is_empty() {
            let hint = if any { " (or * for every game)" } else { "" };
            return Err(self.err(self.line, format!("[{}] needs at least one game ID{hint}", self.kind)));
        }
        self.ids
            .iter()
            .map(|i| {
                let valid = i.chars().all(|c| c.is_ascii_alphanumeric() || "-_.".contains(c)) && i.chars().any(|c| c.is_ascii_alphanumeric());
                if valid { Ok(normalise_id(i)) } else { Err(self.err(self.line, format!("bad game ID `{i}`"))) }
            })
            .collect()
    }

    /// Unknown keys are errors: a typo must not silently disable a field.
    fn finish(&self) -> Result<(), ParseError> {
        match self.fields.first() {
            Some((k, _, l)) => Err(self.err(*l, format!("unknown field `{k}` in [{}]", self.kind))),
            None => Ok(()),
        }
    }

    fn game(mut self, origin: Origin) -> Result<Game, ParseError> {
        let ids = self.ids(false)?;
        let config = match self.take("config") {
            Some((v, l)) => {
                let c = parse_bytes(&v).map_err(|m| self.err(l, format!("config: {m}")))?;
                if c.is_empty() || c.len() > POPS_CONFIG_MAX {
                    return Err(self.err(l, format!("config: a POPS config is 1..={POPS_CONFIG_MAX} bytes, this is {}", c.len())));
                }
                Some(c)
            }
            None => None,
        };
        let switches = match self.take("default") {
            None => Switches::RECOMMENDED,
            Some((v, l)) => {
                let mut s = Switches::default();
                for w in v.split_whitespace() {
                    match Kind::parse(w) {
                        Some(Kind::Fix) => s.fixes = true,
                        Some(Kind::Fps) => s.fps = true,
                        Some(Kind::Ntsc60) => s.ntsc60 = true,
                        _ => return Err(self.err(l, format!("default `{w}`: list the switches that start on: fix, fps, 60hz"))),
                    }
                }
                s
            }
        };
        let libcrypt = match self.take("libcrypt") {
            None => None,
            Some((v, l)) => {
                let n = match v.strip_prefix("0x").or_else(|| v.strip_prefix("0X")) {
                    Some(h) => u16::from_str_radix(h, 16),
                    None => v.parse(),
                };
                Some(n.map_err(|_| self.err(l, format!("libcrypt `{v}`: the magic word is 0..=65535 (or 0x0000..=0xFFFF)")))?)
            }
        };
        let pops_id = match self.take("pops_id") {
            None => None,
            Some((v, l)) => {
                let id = normalise_id(&v);
                let valid = id.len() == 9 && id[..4].bytes().all(|b| b.is_ascii_uppercase()) && id[4..].bytes().all(|b| b.is_ascii_digit());
                if !valid {
                    return Err(self.err(l, format!("pops_id `{v}`: a product code is 4 letters and 5 digits")));
                }
                Some(id)
            }
        };
        let min_level = match self.take("min_level") {
            None => None,
            Some((v, l)) => match v.parse() {
                Ok(n) if psx2psp_core::psar::LEVELS.contains(&n) => Some(n),
                _ => return Err(self.err(l, format!("min_level `{v}`: a deflate level is 1..=9"))),
            },
        };
        let pal60 = match self.take("pal60") {
            None => None,
            Some((v, l)) => match v.to_ascii_lowercase().as_str() {
                "yes" => Some(true),
                "no" => Some(false),
                _ => return Err(self.err(l, format!("pal60 `{v}`: yes or no"))),
            },
        };
        let manual_disc = match self.take("disc_swap") {
            None => None,
            Some((v, l)) => match v.to_ascii_lowercase().as_str() {
                "auto" => Some(false),
                "manual" => Some(true),
                _ => return Err(self.err(l, format!("disc_swap `{v}`: auto or manual"))),
            },
        };
        let mut text = |k: &str| self.take(k).map(|v| v.0).unwrap_or_default();
        let (title, source, note) = (text("title"), text("source"), text("note"));
        self.finish()?;
        Ok(Game { ids, title, config, source, note, switches, libcrypt, pops_id, min_level, pal60, manual_disc, origin })
    }

    fn patch(mut self, origin: Origin) -> Result<Patch, ParseError> {
        let ids = self.ids(true)?;
        let (name, _) = self.require("name")?;
        let (kind, kl) = self.require("kind")?;
        let kind = Kind::parse(&kind).ok_or_else(|| self.err(kl, format!("kind `{kind}`: use fix, fps, 60hz or other")))?;
        let default_on = match self.take("default") {
            None => true,
            Some((v, l)) => match v.to_ascii_lowercase().as_str() {
                "on" | "yes" | "true" => true,
                "off" | "no" | "false" => false,
                _ => return Err(self.err(l, format!("default `{v}`: use on or off"))),
            },
        };
        let md5 = match self.take("md5") {
            None => Vec::new(),
            Some((v, l)) => {
                let m: Vec<String> = v.split_whitespace().map(str::to_ascii_lowercase).collect();
                if let Some(bad) = m.iter().find(|h| h.len() != 32 || !h.bytes().all(|b| b.is_ascii_hexdigit())) {
                    return Err(self.err(l, format!("md5 `{bad}`: 32 hex digits per dump")));
                }
                if m.is_empty() {
                    return Err(self.err(l, "`md5` is empty"));
                }
                m
            }
        };
        let note = self.take("note").map(|v| v.0).unwrap_or_default();
        let mut p = if let Some((v, l)) = self.take("ppf") {
            if let Some((k, _, kl)) = self.fields.iter().find(|f| ["search", "replace", "align"].contains(&f.0.as_str())) {
                return Err(self.err(*kl, format!("`{k}` with `ppf`: a patch is either a PPF or a pattern")));
            }
            let b = parse_bytes(&v).map_err(|m| self.err(l, format!("ppf: {m}")))?;
            PpfPatch::parse(&b).map_err(|e| self.err(l, format!("ppf: {e}")))?;
            let mut p = Patch::new(&[], &name, kind, "00", "00", &note).map_err(|m| self.err(self.line, m))?;
            p.body = Body::Ppf(b);
            p
        } else {
            let align = match self.take("align") {
                None => 4,
                Some((v, l)) => match v.as_str() {
                    "1" | "2" | "4" => v.parse().expect("digit"),
                    _ => return Err(self.err(l, format!("align `{v}`: use 1, 2 or 4"))),
                },
            };
            let (search, sl) = self.require("search")?;
            let (replace, _) = self.require("replace")?;
            let mut p = Patch::new(&[], &name, kind, &search, &replace, &note).map_err(|m| self.err(sl, m))?;
            if let Body::Pattern { align: a, .. } = &mut p.body {
                *a = align;
            }
            p
        };
        self.finish()?;
        (p.ids, p.default_on, p.md5, p.origin) = (ids, default_on, md5, origin);
        Ok(p)
    }
}

fn sections(text: &str) -> Result<Vec<Section<'_>>, ParseError> {
    let mut out: Vec<Section> = Vec::new();
    // The last field may continue on the indented lines that follow it.
    let mut open = false;
    for (i, raw) in text.lines().enumerate() {
        let n = i + 1;
        let raw = raw.trim_start_matches('\u{feff}');
        let t = raw.trim();
        if t.is_empty() {
            open = false;
            continue;
        }
        if t.starts_with(';') || t.starts_with('#') {
            continue;
        }
        if open && raw.starts_with([' ', '\t']) {
            let s = out.last_mut().expect("open implies a section");
            let v = &mut s.fields.last_mut().expect("open implies a field").1;
            if !v.is_empty() {
                v.push(' ');
            }
            v.push_str(t);
            s.end = n;
            continue;
        }
        open = false;
        if let Some(h) = t.strip_prefix('[') {
            let h = h.strip_suffix(']').ok_or(ParseError { line: n, msg: "section header without `]`".into() })?;
            let mut words = h.split_whitespace();
            let kind = words.next().unwrap_or_default();
            if kind != "game" && kind != "patch" {
                return Err(ParseError { line: n, msg: format!("unknown section [{kind}]: use [game IDs…] or [patch IDs…]") });
            }
            out.push(Section { line: n, end: n, kind, ids: words.collect(), fields: Vec::new() });
            continue;
        }
        let (k, v) = t.split_once('=').ok_or_else(|| ParseError { line: n, msg: format!("expected `key = value`, found `{t}`") })?;
        let s = out.last_mut().ok_or(ParseError { line: n, msg: "field before any [game] or [patch] section".into() })?;
        let k = k.trim().to_ascii_lowercase();
        if s.fields.iter().any(|f| f.0 == k) {
            return Err(ParseError { line: n, msg: format!("`{k}` given twice in one section") });
        }
        s.fields.push((k, v.trim().to_owned(), n));
        s.end = n;
        open = true;
    }
    Ok(out)
}

impl PatchDb {
    pub fn parse(text: &str, origin: Origin) -> Result<Self, ParseError> {
        let mut db = PatchDb::default();
        for s in sections(text)? {
            let line = s.line;
            if s.kind == "game" {
                let g = s.game(origin)?;
                if let Some(o) = db.games.iter().find(|o| overlap(&o.ids, &g.ids)) {
                    return Err(ParseError { line, msg: format!("game {} already has a [game] section", o.ids.join("/")) });
                }
                db.games.push(g);
            } else {
                let p = s.patch(origin)?;
                if db.patches.iter().any(|o| o.name.eq_ignore_ascii_case(&p.name) && overlap(&o.ids, &p.ids)) {
                    return Err(ParseError { line, msg: format!("patch “{}” is defined twice for the same game", p.name) });
                }
                db.patches.push(p);
            }
        }
        Ok(db)
    }

    /// The database compiled into the program: `patches.ini` in front of pop-fe's configs.
    pub fn builtin() -> &'static PatchDb {
        static DB: OnceLock<PatchDb> = OnceLock::new();
        DB.get_or_init(|| {
            let popfe = PatchDb::parse(&popfe(), Origin::BuiltIn).expect("built-in popfe.ini is valid");
            popfe.with_user(PatchDb::parse(BUILTIN, Origin::BuiltIn).expect("built-in patches.ini is valid"))
        })
    }

    /// `self` with `user`'s entries in front (they win on lookup).
    pub fn with_user(&self, user: PatchDb) -> PatchDb {
        PatchDb {
            games: user.games.into_iter().chain(self.games.iter().cloned()).collect(),
            patches: user.patches.into_iter().chain(self.patches.iter().cloned()).collect(),
        }
    }

    pub fn game(&self, id: &str) -> Option<&Game> {
        let id = normalise_id(id);
        self.games.iter().find(|g| g.ids.contains(&id))
    }

    /// The first `field` any [`Game`] for `id` defines (user before built-in): a user `[game]`
    /// that only sets a config does not hide pop-fe's LibCrypt word.
    fn game_field<T>(&self, id: &str, field: impl Fn(&Game) -> Option<T>) -> Option<T> {
        let id = normalise_id(id);
        self.games.iter().filter(|g| g.ids.contains(&id)).find_map(field)
    }

    /// The [`Game`] whose POPS config `id` gets: the first that defines one (user before
    /// built-in), so a `[game]` that only sets other fields does not hide pop-fe's config.
    pub fn config_game(&self, id: &str) -> Option<&Game> {
        let id = normalise_id(id);
        self.games.iter().find(|g| g.ids.contains(&id) && g.config.is_some())
    }

    /// Lowest deflate level `id` loads at on a real PSP ([`Game::min_level`]), if it has one.
    pub fn min_level(&self, id: &str) -> Option<u32> {
        self.game_field(id, |g| g.min_level)
    }

    /// Whether the native runtime runs `id` at 60 Hz as PAL60 ([`Game::pal60`]).
    pub fn pal60(&self, id: &str) -> bool {
        self.game_field(id, |g| g.pal60).unwrap_or(false)
    }

    /// Whether the native runtime leaves `id`'s disc change to the player ([`Game::manual_disc`]).
    pub fn manual_disc(&self, id: &str) -> bool {
        self.game_field(id, |g| g.manual_disc).unwrap_or(false)
    }

    /// LibCrypt magic word of `id`, if it is protected.
    pub fn libcrypt(&self, id: &str) -> Option<u16> {
        self.game_field(id, |g| g.libcrypt)
    }

    /// The ID to build `id` as: its [`Game::pops_id`], else `id` itself (normalised). Every
    /// database lookup for the disc uses the result, as pop-fe does.
    pub fn pops_id(&self, id: &str) -> String {
        self.game_field(id, |g| g.pops_id.clone()).unwrap_or_else(|| normalise_id(id))
    }

    /// The switches `id` starts with ([`Game::switches`], else [`Switches::RECOMMENDED`]).
    pub fn default_switches(&self, id: &str) -> Switches {
        self.game(id).map_or(Switches::RECOMMENDED, |g| g.switches)
    }

    /// The patches for `id`, one per name (user before built-in, game-specific before `*`),
    /// ordered by kind and then by file order.
    pub fn patches_for(&self, id: &str) -> Vec<&Patch> {
        let id = normalise_id(id);
        let mut cands: Vec<&Patch> = self.patches.iter().filter(|p| applies_to(&p.ids, &id)).collect();
        cands.sort_by_key(|p| (p.origin == Origin::BuiltIn, p.ids.is_empty()));
        let mut out: Vec<&Patch> = Vec::new();
        for p in cands {
            if !out.iter().any(|q| q.name.eq_ignore_ascii_case(&p.name)) {
                out.push(p);
            }
        }
        out.sort_by_key(|p| p.kind);
        out
    }
}

// ───────────────────────────── the user file ─────────────────────────────

/// The user database: `patches.ini` next to the executable if present (portable install), else
/// in the per-user config directory (`%APPDATA%\PSX2PSP-Reborn`, `~/Library/Application
/// Support/PSX2PSP-Reborn`, `$XDG_CONFIG_HOME/psx2psp-reborn`). The file may not exist yet.
pub fn user_path() -> Option<PathBuf> {
    if let Some(p) = std::env::current_exe().ok().map(|e| e.with_file_name("patches.ini"))
        && p.is_file()
    {
        return Some(p);
    }
    let env = |k| std::env::var_os(k).filter(|v| !v.is_empty()).map(PathBuf::from);
    let dir = if cfg!(windows) {
        env("APPDATA").map(|d| d.join("PSX2PSP-Reborn"))
    } else if cfg!(target_os = "macos") {
        env("HOME").map(|h| h.join("Library/Application Support/PSX2PSP-Reborn"))
    } else {
        env("XDG_CONFIG_HOME").or_else(|| env("HOME").map(|h| h.join(".config"))).map(|d| d.join("psx2psp-reborn"))
    };
    dir.map(|d| d.join("patches.ini"))
}

/// The merged database and what happened to the user file.
#[derive(Debug, Clone)]
pub struct Loaded {
    pub db: PatchDb,
    pub user_path: Option<PathBuf>,
    /// The user file exists but could not be used (its entries are ignored).
    pub error: Option<String>,
}

pub fn load() -> Loaded {
    load_from(user_path())
}

/// Built-in database plus the user file at `path`, if it exists.
pub fn load_from(path: Option<PathBuf>) -> Loaded {
    let base = PatchDb::builtin();
    let user = path.as_deref().filter(|p| p.is_file()).map(|p| {
        let text = std::fs::read_to_string(p).map_err(|e| format!("{}: {e}", p.display()))?;
        PatchDb::parse(&text, Origin::User).map_err(|e| format!("{}: {e} — user patches ignored", p.display()))
    });
    match user {
        Some(Ok(u)) => Loaded { db: base.with_user(u), user_path: path, error: None },
        Some(Err(e)) => Loaded { db: base.clone(), user_path: path, error: Some(e) },
        None => Loaded { db: base.clone(), user_path: path, error: None },
    }
}

const USER_HEADER: &str = "\
; PSX2PSP-Reborn user patches. Same format as the built-in database (see its header):
;   [patch ID…|*]  name, kind (fix|fps|60hz|other), search + replace [+ align] or ppf (hex),
;                  [default], [md5], [note]
;   [game ID…]     title, config (POPS config, hex), source, [default (fix fps 60hz)],
;                  [libcrypt], [pops_id], [min_level (1-9)], [pal60 (yes|no)],
;                  [disc_swap (auto|manual)], note
; Entries here win over the built-in ones: patches by name, games by ID.
";

/// Appends `p` to the user file (created with a short header if missing). The file must parse
/// before and after, and must not already define a patch with that name for those games.
pub fn append_user(path: &Path, p: &Patch) -> Result<(), String> {
    let old = match std::fs::read_to_string(path) {
        Ok(t) => t,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => String::new(),
        Err(e) => return Err(format!("{}: {e}", path.display())),
    };
    let mut new = if old.trim().is_empty() { USER_HEADER.to_owned() } else { old.clone() };
    if !new.ends_with('\n') {
        new.push('\n');
    }
    new.push('\n');
    new += &Patch { origin: Origin::User, ..p.clone() }.to_ini();
    PatchDb::parse(&new, Origin::User).map_err(|e| format!("{}: {e}", path.display()))?;
    write_atomic(path, &new)
}

/// Removes the user `[patch]` section named `name` whose IDs are exactly `ids` (comments and
/// every other section are kept byte for byte). `Ok(false)` if there is none.
pub fn remove_user(path: &Path, name: &str, ids: &[String]) -> Result<bool, String> {
    let text = std::fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))?;
    let secs = sections(&text).map_err(|e| format!("{}: {e}", path.display()))?;
    let Some(s) = secs.iter().find(|s| {
        s.kind == "patch"
            && s.fields.iter().any(|f| f.0 == "name" && f.1.eq_ignore_ascii_case(name))
            && s.ids(true).is_ok_and(|i| i == ids)
    }) else {
        return Ok(false);
    };
    let (from, to) = (s.line, s.end);
    let lines: Vec<&str> = text.lines().collect();
    // Drop the section and one blank line after it.
    let to = if lines.get(to).is_some_and(|l| l.trim().is_empty()) { to + 1 } else { to };
    let mut kept: Vec<&str> = lines[..from - 1].to_vec();
    kept.extend_from_slice(&lines[to..]);
    let mut new = kept.join("\n");
    new.push('\n');
    write_atomic(path, &new)?;
    Ok(true)
}

fn write_atomic(path: &Path, text: &str) -> Result<(), String> {
    let e = |e: std::io::Error| format!("{}: {e}", path.display());
    if let Some(d) = path.parent() {
        std::fs::create_dir_all(d).map_err(e)?;
    }
    let tmp = path.with_extension("ini.tmp");
    let mut f = std::fs::File::create(&tmp).map_err(e)?;
    f.write_all(text.as_bytes()).and_then(|()| f.sync_all()).map_err(e)?;
    drop(f);
    std::fs::rename(&tmp, path).map_err(e)
}

