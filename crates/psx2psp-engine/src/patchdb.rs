    fn sector_with(code: &[u8], at: usize) -> [u8; psx2psp_patching::sector::SECTOR] {
        let mut s = [0u8; psx2psp_patching::sector::SECTOR];
        s[1..11].fill(0xFF);
        s[15] = 2; // Mode 2 Form 1
        s[24 + at..24 + at + code.len()].copy_from_slice(code);
        s
    }

    /// A PPF3 file (no validation block, no undo) with the given records.
    pub(crate) fn ppf_bytes(records: &[(u64, &[u8])]) -> Vec<u8> {
        let mut b = b"PPF30".to_vec();
        b.push(2); // encoding: PPF 3.0
        b.extend([b' '; 50]);
        b.extend([0, 0, 0, 0]); // image type BIN, no validation, no DIZ, no undo
        for (off, data) in records {
            b.extend(off.to_le_bytes());
            b.push(data.len() as u8);
            b.extend(*data);
        }
        b
    }

